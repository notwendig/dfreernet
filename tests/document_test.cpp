#include "document.hpp"
#include <fstream>
#include <iostream>
int main(int argc,char**argv){try{
    if(argc!=3)throw std::runtime_error("Reference .R-net and new output path required");
    const auto original=rnet::read_file(argv[1]);auto doc=rnet::RnetDocument::read(original);
    std::cout<<"Document version "<<doc.header_version<<", repository "<<doc.repository_version<<", files "<<doc.files.size()<<'\n';
    for(auto&f:doc.files)std::cout<<std::hex<<f.id<<std::dec<<" v"<<f.version<<" bytes="<<f.data.size()<<'\n';
    if(doc.files.size()!=16||doc.files.front().id!=0x10002||doc.files.front().data.size()!=218)throw std::runtime_error("Original repository file list differs");
    // Independently recorded from the original fixture, not generated by the
    // layout reader. Verify both group boundaries, including the eighth copy.
    constexpr std::size_t headers[]={14,8,14,6,6,6,10,10,8,6,6,12,14,6,8,6};
    constexpr std::size_t common[]={204,49,436,84,34,32,25,293,3,28,182,418,216,50,160,49};
    constexpr std::size_t repeated[]={0,0,0,0,0,0,0,40,6,0,0,4,30,0,0,0};
    for(std::size_t i=0;i<doc.files.size();++i){
        auto& data=doc.files[i].data;auto layout=rnet::RepositoryLayout::read(data);
        if(layout.header_size!=headers[i]||layout.stride[0]!=common[i]||layout.stride[1]!=repeated[i])throw std::runtime_error("Original payload layout differs");
        if(layout.offset(0,0,0)!=headers[i])throw std::runtime_error("Incorrect first section offset");
        if(repeated[i]&&layout.offset(1,7,0)!=headers[i]+common[i]+7*repeated[i])throw std::runtime_error("Incorrect eighth instance offset");
        bool rejected_index=false;try{layout.offset(1,8,0);}catch(const std::runtime_error&){rejected_index=true;}
        if(!rejected_index)throw std::runtime_error("Ninth instance accepted");
        for(unsigned mutation=0;mutation<3;++mutation){
            auto corrupt=data;if(mutation==0)corrupt[0]^=1;else if(mutation==1)corrupt.pop_back();else corrupt.resize(headers[i]-1);
            bool rejected_layout=false;try{rnet::RepositoryLayout::read(corrupt);}catch(const std::runtime_error&){rejected_layout=true;}
            if(!rejected_layout)throw std::runtime_error("Corrupt or truncated repository layout accepted");
        }
    }
    auto encoded=doc.write();if(encoded!=original)throw std::runtime_error("Document roundtrip changed bytes");
    auto bad=original;bad[0]^=1;bool rejected=false;
    try{rnet::RnetDocument::read(bad);}catch(const std::runtime_error&){rejected=true;}
    if(!rejected)throw std::runtime_error("Header CRC corruption accepted");
    bad=original;bad.pop_back();rejected=false;
    try{rnet::RnetDocument::read(bad);}catch(const std::runtime_error&){rejected=true;}
    if(!rejected)throw std::runtime_error("Truncated document accepted");
    if(std::filesystem::exists(argv[2])&&std::filesystem::equivalent(std::filesystem::weakly_canonical(argv[1]),std::filesystem::weakly_canonical(argv[2])))throw std::runtime_error("Refuse original overwrite");
    std::ofstream f(argv[2],std::ios::binary);if(!f.write(reinterpret_cast<const char*>(encoded.data()),encoded.size()))throw std::runtime_error("Output failed");
    std::cout<<"PASS: all original document bytes preserved; 16 payload layouts and repeated offsets verified; corrupt/truncated input rejected\n";return 0;
}catch(const std::exception&e){std::cerr<<e.what()<<'\n';return 1;}}
